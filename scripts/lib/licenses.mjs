import { existsSync, readdirSync, readFileSync, realpathSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { readJson } from './json.mjs';

/** Licenses allowed for runtime dependencies (Apache-2.0 compatible, permissive). */
export const ALLOWED_LICENSES = new Set([
  '0BSD',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'ISC',
  'MIT',
  'Zlib',
]);

/**
 * @typedef {{ name: string, version: string, license: string, source: string, text: string }} PackageLicense
 * @typedef {{ name: string, version: string, license?: string, repository?: unknown, dependencies?: Record<string, string> }} PackageJson
 */

/**
 * True when an SPDX expression is satisfied by an allowed license (simple `OR` support).
 * @param {string} expression
 */
export function isAllowed(expression) {
  return expression
    .replace(/[()]/g, '')
    .split(/\s+OR\s+/i)
    .some((id) => ALLOWED_LICENSES.has(id.trim()));
}

/**
 * Find a dependency's folder the way Node resolves it: walk up from `fromDir` through node_modules.
 * @param {string} name
 * @param {string} fromDir
 */
function findPackageDir(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const candidate = join(dir, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return realpathSync(candidate);
    const parent = dirname(dir);
    if (parent === dir) throw new Error(`Cannot find installed package ${name} from ${fromDir}`);
    dir = parent;
  }
}

/**
 * @param {string} dir
 */
function readLicenseText(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  return file ? readFileSync(join(dir, file), 'utf8').replace(/\r\n?/g, '\n').trim() : '';
}

/**
 * @param {unknown} repository
 */
function repositoryUrl(repository) {
  const url =
    typeof repository === 'string'
      ? repository
      : typeof repository === 'object' && repository !== null && 'url' in repository
        ? String(repository.url)
        : '';
  const cleaned = url
    .replace(/^git\+/, '')
    .replace(/\.git$/, '')
    .replace(/^github:/, '');
  // npm shorthand "owner/repo" means GitHub.
  return /^[\w.-]+\/[\w.-]+$/.test(cleaned) ? `https://github.com/${cleaned}` : cleaned;
}

/**
 * Runtime dependencies (package.json `dependencies`, recursively), sorted by name.
 * @param {string} root project folder
 * @returns {PackageLicense[]}
 */
export function collectRuntimeLicenses(root) {
  /** @type {Map<string, PackageLicense>} */
  const found = new Map();
  /** @param {Record<string, string>} deps @param {string} fromDir */
  const visit = (deps, fromDir) => {
    for (const name of Object.keys(deps)) {
      const dir = findPackageDir(name, fromDir);
      const pkg = /** @type {PackageJson} */ (readJson(join(dir, 'package.json')));
      const key = `${pkg.name}@${pkg.version}`;
      if (found.has(key)) continue;
      found.set(key, {
        name: pkg.name,
        version: pkg.version,
        license: pkg.license ?? 'UNKNOWN',
        source: repositoryUrl(pkg.repository),
        text: readLicenseText(dir),
      });
      visit(pkg.dependencies ?? {}, dir);
    }
  };
  const rootPkg = /** @type {PackageJson} */ (readJson(join(root, 'package.json')));
  visit(rootPkg.dependencies ?? {}, root);
  return [...found.values()].sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * @param {PackageLicense[]} packages
 * @returns {string[]}
 */
export function licenseProblems(packages) {
  return packages.flatMap((p) => [
    ...(isAllowed(p.license)
      ? []
      : [`${p.name}@${p.version}: license "${p.license}" is not allowed`]),
    ...(p.text ? [] : [`${p.name}@${p.version}: no license file found`]),
  ]);
}

/**
 * THIRD_PARTY_LICENSES.md content. Deterministic: same packages, same text.
 * @param {PackageLicense[]} packages
 */
export function renderLicenses(packages) {
  const lines = [
    '# Third-party licenses',
    '',
    'Generated by `pnpm licenses:update` from the runtime dependencies that ship in `dist/index.html`.',
    'Do not edit by hand. CI fails when this file is out of date.',
    '',
  ];
  for (const p of packages) {
    lines.push(`## ${p.name} ${p.version}`, '', `- License: ${p.license}`);
    if (p.source) lines.push(`- Source: ${p.source}`);
    lines.push('', '```text', p.text, '```', '');
  }
  return lines.join('\n');
}
